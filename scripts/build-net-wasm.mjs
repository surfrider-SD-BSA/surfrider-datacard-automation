/**
 * Build the digit net's WebAssembly kernels (scripts/wasm/net.c) into
 * src/lib/net-wasm-bytes.ts, so the app build needs no C compiler.
 *
 *   node scripts/build-net-wasm.mjs
 *
 * Needs a clang with the wasm32 target (Apple's has it). No linker: an object
 * file with export_name'd functions, no globals and no calls is a loadable
 * module on its own -- it imports only its memory and an (unused) table.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(mkdtempSync(join(tmpdir(), "net-wasm-")), "net.o");
execFileSync("clang", ["--target=wasm32", "-O3", "-msimd128", "-fno-builtin", "-c", "-o", out, join(ROOT, "scripts/wasm/net.c")]);
const bytes = readFileSync(out);
const mod = new WebAssembly.Module(bytes);
const exports = WebAssembly.Module.exports(mod).map((e) => e.name).sort();
if (exports.join() !== "conv,dense") throw new Error(`unexpected exports: ${exports}`);
const imports = WebAssembly.Module.imports(mod).map((i) => `${i.module}.${i.name}`).sort();
if (imports.some((i) => i !== "env.__linear_memory" && i !== "env.__indirect_function_table")) throw new Error(`unexpected imports: ${imports}`);
writeFileSync(
  join(ROOT, "src/lib/net-wasm-bytes.ts"),
  `// Generated by scripts/build-net-wasm.mjs from scripts/wasm/net.c. Do not edit.\nexport const NET_WASM = "${bytes.toString("base64")}";\n`,
);
console.log(`wrote src/lib/net-wasm-bytes.ts (${bytes.length} bytes)`);
